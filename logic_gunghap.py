            return {"relation": "귀문(鬼門)", "status": "비정상적 집착", "desc": "침소에 귀문관살이 뻗쳐있습니다. 상대에 대한 과도한 의심, 집착, 혹은 신경질적인 반응으로 감정 소모가 매우 심한 궁합입니다."}

