    def _get_root_number(self, year: int) -> int:
        """연도의 각 자리 숫자를 더해 한 자릿수가 될 때까지 반복 연산"""
        r = sum(int(digit) for digit in str(year))
        while r > 9:
            r = sum(int(digit) for digit in str(r))
        return r

    def get_samwon_gapja(self, year: int) -> dict:
        """180년 주기의 삼원갑자(상원/중원/하원갑) 시대 도출"""
        offset = year - 1864
        if offset < 0:
            return {"name": "알 수 없음", "desc": "측정 범위를 벗어났습니다."}
            
        cycle = (offset % 180) // 60
        
        if cycle == 0:
            return {"name": "상원갑(上元甲)", "desc": "만물이 태동하고 새롭게 시작되는 양(陽)의 기운이 팽배한 시대"}
        elif cycle == 1:
            return {"name": "중원갑(中元甲)", "desc": "문명과 제도가 무르익고 기운이 중화되는 만개의 시대"}
        else:
            return {"name": "하원갑(下元甲)", "desc": "물질명리가 극에 달하고 정신적 성숙이 요구되는 음(陰)의 시대"}

    def get_bonmyeongseong(self, year: int, gender: str) -> dict:
        """남녀의 타고난 구궁 본명성(本命星) 연산"""
        root_num = self._get_root_number(year)
        
        if gender == 'M':
            star_num = (11 - root_num) % 9
        else:
            star_num = (4 + root_num) % 9
            
        if star_num == 0:
            star_num = 9
            
        return {"number": star_num, "name": self.stars[star_num]}

