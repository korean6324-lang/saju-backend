    def get_inner_compatibility(self, m_day_branch: str, f_day_branch: str) -> dict:
        """
        남녀 일지(日支) 교차를 통한 부부 침소의 은밀한 속궁합 분석
        충, 합, 원진, 귀문은 물론 파(破), 해(害)까지 정밀 스캔합니다.
        """
        if m_day_branch == f_day_branch:
            return {
                "relation": "비화(比和)",
                "status": "친구 같은 부부",
                "desc": "속궁합의 기운이 동일합니다. 불타오르는 열정보다는 평생을 함께할 편안하고 담백한 동반자적 결합입니다."
            }

        pair = {m_day_branch, f_day_branch}
        
        # 합(合) 체크
        if pair in self.relations["육합(六合)"]:
            return {"relation": "육합(六合)", "status": "천상의 속궁합", "desc": "속궁합이 육합으로 강력하게 결속되어 있습니다. 겉보기엔 무심해도 침소에 들면 어떠한 외부의 위기도 부부의 정으로 쉽게 넘깁니다."}
        
        for samhap in self.relations["삼합(三合)"]:
            if pair.issubset(samhap):
                return {"relation": "반합(半合)", "status": "의리와 안정의 결합", "desc": "서로의 부족한 점을 든든하게 채워주는 궁합입니다. 뜻이 잘 맞고 속궁합이 무던하여 큰 다툼 없이 가정을 번창시킵니다."}

        # 흉(凶) 체크
        if pair in self.relations["충(沖)"]:
            return {"relation": "충(沖)", "status": "깨어짐과 갈등", "desc": "일지가 정면으로 부딪칩니다. 속궁합이 엇나가고 예민한 곳을 찌르니, 거리가 가까워질수록 알 수 없는 짜증이 솟구칩니다. 적절한 거리두기가 필수입니다."}
            
        if pair in self.relations["원진(怨嗔)"]:
            return {"relation": "원진(怨嗔)", "status": "지독한 애증의 살", "desc": "서로 등을 돌리고 원망하면서도, 막상 떨어지면 뼈저리게 그리워지는 벗어날 수 없는 지독한 인연입니다."}
            
