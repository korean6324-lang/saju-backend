    def _get_root_number(self, year: int) -> int:
        r = sum(int(digit) for digit in str(year))
        while r > 9:
            r = sum(int(digit) for digit in str(r))
        return r

    def get_samwon_gapja(self, year: int, lang: str = "ko") -> dict:
        offset = year - 1864
        l_db = self.samwon_db.get(lang, self.samwon_db["ko"])
        if offset < 0: return {"name": l_db[6], "desc": l_db[7]}
            
        cycle = (offset % 180) // 60
        if cycle == 0: return {"name": l_db[0], "desc": l_db[1]}
        elif cycle == 1: return {"name": l_db[2], "desc": l_db[3]}
        else: return {"name": l_db[4], "desc": l_db[5]}

    def get_bonmyeongseong(self, year: int, gender: str) -> dict:
        root_num = self._get_root_number(year)
        if gender == 'M': star_num = (11 - root_num) % 9
        else: star_num = (4 + root_num) % 9
        if star_num == 0: star_num = 9
        # 한자는 전 국가 동일하게 표시 (예: 일백수성(一白水星) -> 그대로 유지하거나, 언어팩을 적용할 수 있으나 여기서는 공통어 유지)
        return {"number": star_num, "name": self.stars[star_num]}

