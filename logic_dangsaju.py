    def calculate_12_stars(self, y_branch: str, lunar_month: int, lunar_day: int, h_branch: str) -> dict:
        """
        🚨 [CTO 지시사항 2 & 3] 정통 당사주 순차 연산 및 시간 모름(unknown_time) 방어 로직
        """
        # 🚨 [보안 추가] 입력값 타입 검증 및 캐스팅으로 서버 다운(500 에러) 원천 차단
        try:
            y_branch = str(y_branch).strip() if y_branch else ""
            h_branch = str(h_branch).strip() if h_branch else ""
            lunar_month = int(lunar_month)
            lunar_day = int(lunar_day)
        except (ValueError, TypeError):
            # 변환 불가능한 비정상 데이터가 유입되면 안전하게 빈 딕셔너리 반환
            return {}

        if y_branch not in self.branches:
            return {}

        # 1. 연성(초년)
        y_idx = self.branches.index(y_branch)
        
        # 2. 월성(청년)
        m_idx = (y_idx + lunar_month - 1) % 12
        
        # 3. 일성(중년)
        d_idx = (m_idx + lunar_day - 1) % 12
        
        # 4. 시성(말년) - 시간 모름 방어 로직
        h_idx = None
        if h_branch in self.branches:
            h_branch_idx = self.branches.index(h_branch)
            h_idx = (d_idx + h_branch_idx) % 12

        # 결과 매핑
        stages = {
            "초년운 (연성)": self.branches[y_idx],
            "청년운 (월성)": self.branches[m_idx],
            "중년운 (일성)": self.branches[d_idx],
            "말년운 (시성)": self.branches[h_idx] if h_idx is not None else "-"
        }

        result = {}
        life_stage_keys = ["초년", "청년", "중년", "말년"]
        
        for i, (stage_name, branch) in enumerate(stages.items()):
            stage_period = life_stage_keys[i]
            
            if branch == "-":
                result[stage_name] = {
                    "name_clean": "시간 모름",
                    "hanja_clean": "時柱未詳",
                    "desc": "태어난 시간을 알 수 없어 말년의 운명을 판별할 수 없습니다. (연산 불가)"
                }
            else:
                star_key = self.star_map[branch]
                db_data = self.interpretation_db[star_key]
                result[stage_name] = {
                    "name_clean": db_data["name"],
                    "hanja_clean": db_data["hanja"],
                    "desc": db_data[stage_period]
                }
                
        return result