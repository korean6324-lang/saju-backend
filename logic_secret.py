    def _calculate_critical_ages(self, bazi_data: dict, daewun_data: dict) -> dict:
        day_stem = bazi_data.get("day", {}).get("stem", "")
        day_branch = bazi_data.get("day", {}).get("branch", "")

        if not day_stem or not day_branch or day_stem == "-" or day_branch == "-":
            return {
                "ages": [],
                "message": "일주(태어난 날) 정보가 손실되어 천극지충의 위기 나이를 도출할 수 없습니다."
            }

        # 일주를 정면으로 깨부수는 천간과 지지 도출
        target_stem = self.stem_clash.get(day_stem)
        target_branch = self.branch_clash.get(day_branch)

        critical_ages = []

        # 대운(10년 운) 배열에서 천극지충 스캔
        timeline = daewun_data.get("timeline", [])
        for dw in timeline:
            if dw.get("stem") == target_stem and dw.get("branch") == target_branch:
                age = dw.get("age")
                if age is not None:
                    critical_ages.append(int(age))

        if critical_ages:
            age_str = ", ".join([f"{age}세" for age in critical_ages])
            msg = f"당신 나이 {age_str}를 기점으로 10년간 천극지충(天剋地沖)의 무서운 흉액이 도사리고 있습니다. 해당 나이에 인생의 뿌리가 송두리째 흔들리는 강제적 이직, 이혼수, 혹은 건강상의 치명적 변동이 발생하니 납작 엎드려 수성(守城)하십시오."
        else:
            msg = "현재의 대운 흐름 상으로 일주를 정면으로 깨부수는 '천극지충'의 거대한 흉액 구간은 발견되지 않았습니다. 하늘의 치명적인 억까는 피한 형국입니다."

        return {
            "ages": critical_ages,
            "message": msg
        }

